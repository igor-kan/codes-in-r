set.seed(123)
A <- cbind(1, 1:10, (1:10)^2 * 0.1)
y <- 2.0 + 3.0 * A[, 2] - 4.0 * A[, 3] + rnorm(10, sd = 1e-3)
qr_res <- mgs_decompose(A)
verify_mgs_qr(A, qr_res)
beta_mgs <- mgs_solve(qr_res, y)
beta_lm <- unname(stats::lm.fit(A, y)$coefficients)
stopifnot(max(abs(beta_mgs - beta_lm)) < 1e-10)
