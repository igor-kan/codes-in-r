check_numeric_vec(c(1.0, 2.0))
x <- c(1, 2, 3, 4, 5)
r <- lin_ccc(x, x)
stopifnot(abs(r$ccc - 1.0) < 1e-12)
stopifnot(abs(r$rho - 1.0) < 1e-12)
stopifnot(abs(r$cb - 1.0) < 1e-12)
stopifnot(r$n == 5L)
y <- 2.0 * x
r2 <- lin_ccc(x, y)
stopifnot(abs(r2$rho - 1.0) < 1e-12)
stopifnot(r2$ccc > 0.0 && r2$ccc < 1.0)
stopifnot(abs(r2$ccc - r2$rho * r2$cb) < 1e-12)
stopifnot(abs(r2$ccc - lin_ccc(y, x)$ccc) < 1e-12)
r3 <- lin_ccc(x, x + 10.0)
stopifnot(abs(r3$rho - 1.0) < 1e-12 && r3$ccc < 1.0)
