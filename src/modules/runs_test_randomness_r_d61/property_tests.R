set.seed(31)
x <- rbinom(80, 1, 0.5)
r <- runs_test(x)
stopifnot(r$runs >= 1L && r$runs <= 80L)
stopifnot(r$p_value >= 0.0 && r$p_value <= 1.0)
stopifnot(r$n1 + r$n2 == 80L)
comp <- runs_test(1 - x)
stopifnot(comp$runs == r$runs)
stopifnot(comp$n1 == r$n2 && comp$n2 == r$n1)
stopifnot(abs(comp$p_value - r$p_value) < 1e-12)
rev <- runs_test(rev(x))
stopifnot(rev$runs == r$runs)
stopifnot(abs(rev$statistic - r$statistic) < 1e-12)
stopifnot(abs(rev$p_value - r$p_value) < 1e-12)
expected <- 2.0 * r$n1 * r$n2 / (r$n1 + r$n2) + 1.0
variance <- 2.0 * r$n1 * r$n2 * (2.0 * r$n1 * r$n2 - r$n1 - r$n2) /
  ((r$n1 + r$n2)^2 * (r$n1 + r$n2 - 1.0))
stopifnot(abs(r$statistic - (r$runs - expected) / sqrt(variance)) < 1e-12)
