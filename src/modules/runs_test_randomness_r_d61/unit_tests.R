check_numeric_vec(c(1.0, 2.0))
x <- c(0, 1, 0, 1, 0, 1)
r <- runs_test(x)
stopifnot(r$runs == 6L && r$n1 == 3L && r$n2 == 3L)
z <- (6.0 - 4.0) / sqrt(1.2)
stopifnot(abs(r$statistic - z) < 1e-12)
stopifnot(abs(r$p_value - 2.0 * pnorm(-abs(z))) < 1e-12)
b <- c(0, 0, 0, 1, 1, 1)
rb <- runs_test(b)
stopifnot(rb$runs == 2L)
stopifnot(abs(rb$statistic + z) < 1e-12)
stopifnot(abs(rb$p_value - r$p_value) < 1e-12)
r2 <- runs_test(2.0 * x + 7.0)
stopifnot(r2$runs == r$runs && abs(r2$statistic - r$statistic) < 1e-12)
bad <- try(runs_test(c(0, 0, 0)), silent = TRUE)
stopifnot(inherits(bad, "try-error"))
